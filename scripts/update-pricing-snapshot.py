#!/usr/bin/env python3
"""Regenerates Sources/Headroom/PricingSnapshot.swift from one pinned LiteLLM commit (R6).

Usage:
    scripts/update-pricing-snapshot.py COMMIT_SHA SOURCE_SHA256 [--file PATH] [--retrieved YYYY-MM-DDTHH:MM:SSZ]

1. Gets model_prices_and_context_window.json at exactly COMMIT_SHA (never a branch), or reads PATH if given.
2. Refuses to continue unless the file's SHA-256 equals SOURCE_SHA256. Review the upstream diff first and take the
   checksum from your own download; the script never trusts a checksum it computed itself.
3. Extracts the Claude entries with the same rules as `Pricing.extract` in Ledger.swift, validates them and writes a
   deterministic Swift file (sorted keys, fixed formatting) with the source URL, commit, checksums, retrieval time and
   the LiteLLM MIT notice.

The output is reviewed and committed like code. The app never fetches a newer revision on its own.
"""
import argparse
import hashlib
import json
import math
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO = "BerriAI/litellm"
PATH = "model_prices_and_context_window.json"
OUT = Path(__file__).resolve().parent.parent / "Sources/Headroom/PricingSnapshot.swift"
MAX_PRICE = 1e-3  # USD per token; anything above is treated as malformed (Pricing.maxPrice)


def number(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else None


def extract(json_obj):
    if not isinstance(json_obj, dict):
        sys.exit("source is not a JSON object")
    table = {}
    for key, v in json_obj.items():
        if not key.startswith("claude") or not isinstance(v, dict):
            continue
        inp, out = number(v.get("input_cost_per_token")), number(v.get("output_cost_per_token"))
        if inp is None or out is None:
            continue
        w = number(v.get("cache_creation_input_token_cost"))
        w1h = number(v.get("cache_creation_input_token_cost_above_1hr"))
        r = number(v.get("cache_read_input_token_cost"))
        table[key] = {
            "input": float(inp),
            "output": float(out),
            "cacheWrite": float(w) if w is not None else inp * 1.25,
            "cacheWrite1h": float(w1h) if w1h is not None else inp * 2,
            "cacheRead": float(r) if r is not None else inp * 0.1,
        }
    if not table:
        sys.exit("no Claude prices extracted")
    for key, p in table.items():
        for f, x in p.items():
            if not math.isfinite(x) or x < 0 or x > MAX_PRICE:
                sys.exit(f"{key}.{f} out of range: {x}")
    return table


TEMPLATE = """// Generated by scripts/update-pricing-snapshot.py. Do not edit by hand; rerun the script and review the diff.
//
// Claude prices extracted from LiteLLM's model_prices_and_context_window.json at one pinned commit (R6).
// LiteLLM, MIT License, Copyright (c) 2023 Berri AI. https://github.com/@REPO@

/// The reviewed price snapshot built into SpanDeck. Costs computed from it are estimates at list prices, not a bill.
enum PricingSnapshot {
    static let pin = PricingPin(revision: "@COMMIT@",
                                sourceSHA256: "@SOURCE_SHA@")
    /// When the pinned file was retrieved for review (UTC).
    static let retrieved = "@RETRIEVED@"
    static let bundled = PricingBundle(revision: pin.revision, sourceSHA256: pin.sourceSHA256, retrieved: retrieved,
                                       tableSHA256: "@TABLE_SHA@",
                                       tableJSON: tableJSON)
    static let license = "LiteLLM price data, MIT License, Copyright (c) 2023 Berri AI"

    /// @COUNT@ entries. SHA-256 of this text (UTF-8) is `bundled.tableSHA256`.
    private static let tableJSON = #\"\"\"
@TABLE_JSON@
\"\"\"#
}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("commit")
    ap.add_argument("sha256")
    ap.add_argument("--file")
    ap.add_argument("--retrieved", default=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"))
    a = ap.parse_args()
    if len(a.commit) != 40 or any(c not in "0123456789abcdef" for c in a.commit):
        sys.exit("commit must be a full 40-character lowercase SHA, not a branch or tag")
    url = f"https://raw.githubusercontent.com/{REPO}/{a.commit}/{PATH}"
    if a.file:
        data = Path(a.file).read_bytes()
    else:
        with urllib.request.urlopen(url, timeout=30) as resp:
            data = resp.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != a.sha256.lower():
        sys.exit(f"checksum mismatch: got {digest}, expected {a.sha256}")
    table = extract(json.loads(data))
    table_json = json.dumps(table, sort_keys=True, indent=1, separators=(",", ": "))
    table_sha = hashlib.sha256(table_json.encode()).hexdigest()
    swift = TEMPLATE
    for k, v in {"COMMIT": a.commit, "SOURCE_SHA": digest, "RETRIEVED": a.retrieved, "TABLE_SHA": table_sha,
                 "COUNT": str(len(table)), "REPO": REPO, "TABLE_JSON": table_json}.items():
        swift = swift.replace("@" + k + "@", v)
    OUT.write_text(swift)
    print(f"wrote {OUT.relative_to(OUT.parent.parent.parent)}: {len(table)} entries, source {digest}, table {table_sha}")


if __name__ == "__main__":
    main()
